// Update order status (seller only)
export const updateOrderStatus = async (req, res) => {
  try {
    const { id } = req.params;
    const { status } = req.body;
    const userId = req.user.id;

    const order = await Order.findById(id);
    if (!order) {
      return res.status(404).json({ message: "Order not found" });
    }

    // Only seller can update order status
    if (order.sellerId.toString() !== userId) {
      return res.status(403).json({ message: "Only seller can update order status" });
    }

    // Validate status transition
    const validStatuses = ["pending", "confirmed", "shipped", "delivered", "cancelled"];
    if (!validStatuses.includes(status)) {
      return res.status(400).json({ message: "Invalid status" });
    }

    order.status = status;
    await order.save();

    const updatedOrder = await Order.findById(id)
      .populate("buyerId", "name email")
      .populate("sellerId", "name email phone")
      .populate("mobileId");

    res.json(updatedOrder);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// Upload payment proof (buyer only)
export const uploadPaymentProof = async (req, res) => {
  try {
    const { id } = req.params;
    const userId = req.user.id;

    if (!req.file) {
      return res.status(400).json({ message: "No file uploaded" });
    }

    const order = await Order.findById(id);
    if (!order) {
      return res.status(404).json({ message: "Order not found" });
    }

    // Only buyer can upload payment proof
    if (order.buyerId.toString() !== userId) {
      return res.status(403).json({ message: "Only buyer can upload payment proof" });
    }

    // Update order with payment proof URL
    order.paymentProofUrl = `/uploads/payment-proofs/${req.file.filename}`;
    await order.save();

    const updatedOrder = await Order.findById(id)
      .populate("buyerId", "name email")
      .populate("sellerId", "name email phone")
      .populate("mobileId");

    res.json(updatedOrder);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// Confirm payment (seller only)
export const confirmPayment = async (req, res) => {
  try {
    const { id } = req.params;
    const userId = req.user.id;

    const order = await Order.findById(id);
    if (!order) {
      return res.status(404).json({ message: "Order not found" });
    }

    // Only seller can confirm payment
    if (order.sellerId.toString() !== userId) {
      return res.status(403).json({ message: "Only seller can confirm payment" });
    }

    order.paymentStatus = "confirmed";
    order.paymentConfirmedAt = new Date();
    order.status = "confirmed";
    await order.save();

    const updatedOrder = await Order.findById(id)
      .populate("buyerId", "name email")
      .populate("sellerId", "name email phone")
      .populate("mobileId");

    res.json(updatedOrder);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};
