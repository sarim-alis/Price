import Order from "../../models/Order.js";
import Mobile from "../../models/Mobile.js";
import User from "../../models/User.js";

// Create new order
export const createOrder = async (req, res) => {
  try {
    const { mobileId, paymentMethod, sellerPaymentInfo } = req.body;
    const buyerId = req.user.id;

    // Validate mobile exists
    const mobile = await Mobile.findById(mobileId).populate("sellerId");
    if (!mobile) {
      return res.status(404).json({ message: "Mobile not found" });
    }

    if (mobile.status !== "active") {
      return res.status(400).json({ message: "Mobile is not available for purchase" });
    }

    // Create order
    const order = await Order.create({
      orderNumber: "", // Will be auto-generated by pre-save hook
      buyerId,
      sellerId: mobile.sellerId._id,
      mobileId,
      price: mobile.price,
      paymentMethod,
      sellerPaymentInfo: sellerPaymentInfo || {}
    });

    // Populate order details
    const populatedOrder = await Order.findById(order._id)
      .populate("buyerId", "name email")
      .populate("sellerId", "name email phone")
      .populate("mobileId");

    res.status(201).json(populatedOrder);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// Get order by ID
export const getOrderById = async (req, res) => {
  try {
    const { id } = req.params;
    const userId = req.user.id;

    const order = await Order.findById(id)
      .populate("buyerId", "name email")
      .populate("sellerId", "name email phone")
      .populate("mobileId");

    if (!order) {
      return res.status(404).json({ message: "Order not found" });
    }

    // Check if user is buyer or seller
    if (order.buyerId._id.toString() !== userId && order.sellerId._id.toString() !== userId) {
      return res.status(403).json({ message: "Access denied" });
    }

    res.json(order);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// Get buyer's orders
export const getBuyerOrders = async (req, res) => {
  try {
    const buyerId = req.user.id;
    const { status } = req.query;

    const query = { buyerId };
    if (status) {
      query.status = status;
    }

    const orders = await Order.find(query)
      .populate("sellerId", "name email phone")
      .populate("mobileId")
      .sort({ createdAt: -1 });

    res.json(orders);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

